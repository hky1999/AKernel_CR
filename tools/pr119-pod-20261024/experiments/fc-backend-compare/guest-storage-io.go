// guest-storage-io is an acceptance workload, not a sandboxd component.
package main

import (
	"crypto/sha256"
	"encoding/hex"
	"encoding/json"
	"flag"
	"fmt"
	"io"
	"math/rand"
	"os"
	"path/filepath"
	"time"
)

type operation struct {
	Offset  int64 `json:"offset"`
	WriteNS int64 `json:"write_ns"`
	SyncNS  int64 `json:"sync_ns"`
	TotalNS int64 `json:"total_ns"`
}

type result struct {
	Bytes           int         `json:"bytes"`
	Seed            int64       `json:"seed"`
	BlockBytes      int         `json:"block_bytes"`
	BufferFillNS    int64       `json:"buffer_fill_ns"`
	OpenNS          int64       `json:"open_ns"`
	WriteNS         int64       `json:"sequential_write_ns"`
	FileSyncNS      int64       `json:"sequential_file_sync_ns"`
	DirectorySyncNS int64       `json:"sequential_directory_sync_ns"`
	SequentialNS    int64       `json:"sequential_total_ns"`
	Operations      []operation `json:"random_sync_operations"`
	SHA256          string      `json:"file_sha256_after"`
	Verified        bool        `json:"readback_verified"`
	Scope           string      `json:"clock_scope"`
}

func run() error {
	path := flag.String("path", "", "new absolute private guest file")
	bytes := flag.Int("bytes", 64<<20, "payload bytes, a multiple of 4096")
	ops := flag.Int("ops", 64, "4 KiB random overwrite and fsync operations")
	seed := flag.Int64("seed", 20261024, "identical deterministic payload for both backends")
	flag.Parse()
	const blockBytes = 4096
	if !filepath.IsAbs(*path) || *bytes < blockBytes || *bytes > 256<<20 || *bytes%blockBytes != 0 || *ops < 0 || *ops > 1024 {
		return fmt.Errorf("invalid workload parameters")
	}
	r := result{Bytes: *bytes, Seed: *seed, BlockBytes: blockBytes, Operations: make([]operation, 0, *ops), Scope: "guest monotonic clock; excludes SDK RPC, buffer generation and final verification; total sequential includes create/write/file fsync/directory fsync"}
	rng := rand.New(rand.NewSource(*seed))
	buffer := make([]byte, *bytes)
	begin := time.Now()
	if n, err := rng.Read(buffer); err != nil || n != len(buffer) {
		return fmt.Errorf("payload generation: bytes=%d error=%v", n, err)
	}
	r.BufferFillNS = time.Since(begin).Nanoseconds()
	sequentialBegin := time.Now()
	begin = time.Now()
	f, err := os.OpenFile(*path, os.O_CREATE|os.O_EXCL|os.O_RDWR, 0600)
	if err != nil {
		return err
	}
	defer f.Close()
	r.OpenNS = time.Since(begin).Nanoseconds()
	begin = time.Now()
	if n, err := f.Write(buffer); err != nil || n != len(buffer) {
		return fmt.Errorf("sequential write: bytes=%d error=%v", n, err)
	}
	r.WriteNS = time.Since(begin).Nanoseconds()
	begin = time.Now()
	if err := f.Sync(); err != nil {
		return err
	}
	r.FileSyncNS = time.Since(begin).Nanoseconds()
	begin = time.Now()
	directory, err := os.Open(filepath.Dir(*path))
	if err != nil {
		return err
	}
	err = directory.Sync()
	closeErr := directory.Close()
	if err != nil {
		return err
	}
	if closeErr != nil {
		return closeErr
	}
	r.DirectorySyncNS = time.Since(begin).Nanoseconds()
	r.SequentialNS = time.Since(sequentialBegin).Nanoseconds()
	block := make([]byte, blockBytes)
	for i := 0; i < *ops; i++ {
		offset := rng.Int63n(int64(*bytes/blockBytes)) * blockBytes
		if n, err := rng.Read(block); err != nil || n != len(block) {
			return fmt.Errorf("overwrite generation: bytes=%d error=%v", n, err)
		}
		total := time.Now()
		begin = time.Now()
		if n, err := f.WriteAt(block, offset); err != nil || n != len(block) {
			return fmt.Errorf("random write: bytes=%d error=%v", n, err)
		}
		writeNS := time.Since(begin).Nanoseconds()
		begin = time.Now()
		if err := f.Sync(); err != nil {
			return err
		}
		syncNS := time.Since(begin).Nanoseconds()
		r.Operations = append(r.Operations, operation{Offset: offset, WriteNS: writeNS, SyncNS: syncNS, TotalNS: time.Since(total).Nanoseconds()})
		copy(buffer[int(offset):int(offset)+blockBytes], block)
	}
	expected := sha256.Sum256(buffer)
	if _, err := f.Seek(0, io.SeekStart); err != nil {
		return err
	}
	hash := sha256.New()
	if n, err := io.Copy(hash, f); err != nil || n != int64(len(buffer)) {
		return fmt.Errorf("readback: bytes=%d error=%v", n, err)
	}
	r.SHA256 = hex.EncodeToString(hash.Sum(nil))
	if r.SHA256 != hex.EncodeToString(expected[:]) {
		return fmt.Errorf("readback differs from generated bytes")
	}
	r.Verified = true
	if err := f.Close(); err != nil {
		return err
	}
	return json.NewEncoder(os.Stdout).Encode(r)
}

func main() {
	if err := run(); err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
}
